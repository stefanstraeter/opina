import { existsSync, writeFileSync } from 'node:fs';

const ENV_FILE = '.env';
const TARGET_FILE = 'src/environments/environment.ts';
const REQUIRED_KEYS = ['SUPABASE_URL', 'SUPABASE_ANON_KEY'];

if (existsSync(ENV_FILE)) {
  process.loadEnvFile(ENV_FILE);
}

const missingKeys = REQUIRED_KEYS.filter((key) => !process.env[key]);
if (missingKeys.length > 0) {
  console.error(`Missing environment values: ${missingKeys.join(', ')}`);
  console.error('Create a .env file (see .env.example) or set them as variables.');
  process.exit(1);
}

const content = `// Generated by scripts/set-env.mjs - do not edit, do not commit.
export const environment = {
  supabaseUrl: '${process.env.SUPABASE_URL}',
  supabaseAnonKey: '${process.env.SUPABASE_ANON_KEY}',
};
`;

writeFileSync(TARGET_FILE, content);
console.log(`Wrote ${TARGET_FILE}`);
